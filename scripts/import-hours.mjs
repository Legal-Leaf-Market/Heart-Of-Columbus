// node scripts/import-hours.mjs <maps-hours.json>
// Second Google Maps pass: writes src/data/hours.mjs, and folds any website,
// phone, action links or closed flags it found into scripts/data/
// maps-lookup.json (recovering businesses the first pass missed). Re-run
// scripts/import-web.mjs afterwards.
import { readFileSync, writeFileSync } from 'node:fs';
import { parseWeek } from '../src/hours.mjs';

const fresh = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const lookupPath = new URL('./data/maps-lookup.json', import.meta.url);
const lookup = JSON.parse(readFileSync(lookupPath, 'utf8'));

const hours = {};
let recovered = 0, filled = 0, bad = 0;
for (const [slug, r] of Object.entries(fresh).sort()) {
  if (r.miss || !r.h) continue;
  const rows = parseWeek(r.hr);
  if (rows) hours[slug] = rows;
  else if (r.hr) bad++;
  const old = lookup[slug];
  if (!old || old.miss || !old.h) {
    lookup[slug] = { h: r.h, ...(r.w ? { w: r.w } : {}), ...(r.p ? { p: r.p } : {}), ...(r.o ? { o: r.o } : {}), ...(r.c ? { c: r.c } : {}), ...(r.x ? { x: 1 } : {}), ...(r.t ? { t: 1 } : {}) };
    recovered++;
  } else {
    for (const k of ['w', 'p', 'o', 'c']) if (!old[k] && r[k]) { old[k] = r[k]; filled++; }
    if (r.x) old.x = 1;
    if (r.t) old.t = 1; else delete old.t;
  }
}
writeFileSync(lookupPath, JSON.stringify(lookup));
const head = `// Opening hours per business, from each business's own Google Maps listing,
// October 2026. Rows are [day, open, close]: day 0 = Sunday, minutes after
// midnight, a close past midnight is > 1440. Generated by scripts/import-hours.mjs.
`;
writeFileSync(new URL('../src/data/hours.mjs', import.meta.url), head + 'export const HOURS = ' + JSON.stringify(hours) + ';\n');
console.log(Object.keys(hours).length, 'with hours;', recovered, 'recovered from misses;', filled, 'fields filled;', bad, 'unparsed');
