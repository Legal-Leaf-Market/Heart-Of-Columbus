// node scripts/import-attrs.mjs [scripts/data/osm-attrs.json]
// Matches the OpenStreetMap places pulled by scripts/pull-osm-attrs.mjs to
// directory listings and writes src/data/attrs.mjs. A match needs the same
// house number and street within 150 m plus a shared word in the name (one
// address can hold a hospital and a clinic), or, where the map has no
// address, a shared distinctive word in the name within 40 m. Map entries
// that are not a business (churches, hospitals, cemeteries) are skipped. Anything else, and any
// element two listings could claim, goes to scripts/data/attrs-unmatched.json
// for a person. Branded (chain) map entries are skipped.
import { readFileSync, writeFileSync } from 'node:fs';
import { directory, km } from '../src/data/directory.mjs';

const raw = JSON.parse(readFileSync(process.argv[2] || new URL('./data/osm-attrs.json', import.meta.url), 'utf8'));
const STOP = new Set(['the', 'and', 'of', 'columbus', 'restaurant', 'grill', 'bar', 'cafe', 'shop', 'store', 'company', 'co', 'inc', 'llc', 'indiana', 'in', 'mexican', 'pizza', 'coffee', 'salon', 'church', 'center', 'north', 'south', 'east', 'west']);
const LIGHT = new Set(['the', 'and', 'our']);
const NOT_BUSINESS = new Set(['place_of_worship', 'hospital', 'grave_yard', 'school', 'parking', 'toilets', 'townhall', 'police', 'fire_station']);
const all = (s) => new Set(String(s || '').toLowerCase().normalize('NFD').replace(/[^a-z0-9 ]/g, ' ').split(/\s+/).filter((w) => w.length > 2 && !LIGHT.has(w)));
const words = (s) => new Set(String(s || '').toLowerCase().normalize('NFD').replace(/[^a-z0-9 ]/g, ' ').split(/\s+/).filter((w) => w.length > 2 && !STOP.has(w)));
const street = (s) => String(s || '').toLowerCase().replace(/\b(n|s|e|w|north|south|east|west|st|street|ave|avenue|rd|road|dr|drive|blvd|ln|lane|pkwy|parkway|ct|way|hwy)\b\.?/g, '').replace(/[^a-z0-9]/g, '');
const num = (a) => (String(a || '').match(/^(\d+)\s/) || [])[1];
const streetOf = (a) => street(String(a || '').replace(/^\d+\s+/, '').replace(/#.*$/, ''));

export function match(el, list = directory) {
  const t = el.tags;
  if (t.brand) return { why: 'brand' };
  if (NOT_BUSINESS.has(t.amenity)) return { why: 'not a business' };
  const near = list.filter((b) => b.ll && km(b.ll, el.ll) <= 0.15);
  let hits = [];
  if (t['addr:housenumber'] && t['addr:street']) {
    const nw = all(t.name);
    hits = near.filter((b) => num(b.address) === t['addr:housenumber'] && streetOf(b.address) === street(t['addr:street']) && [...all(b.name)].some((w) => nw.has(w)));
  } else {
    const nw = words(t.name);
    hits = near.filter((b) => km(b.ll, el.ll) <= 0.04 && [...words(b.name)].some((w) => nw.has(w)));
  }
  if (hits.length === 1) return { slug: hits[0].slug };
  return { why: hits.length ? 'ambiguous' : 'no listing' };
}

const pick = (t) => {
  const a = {};
  if (['yes', 'limited', 'no'].includes(t.wheelchair)) a.wheelchair = t.wheelchair;
  if (['yes', 'leashed', 'no'].includes(t.dog)) a.dog = t.dog === 'leashed' ? 'yes' : t.dog;
  if (t.outdoor_seating === 'yes' || t.outdoor_seating === 'no') a.outdoor = t.outdoor_seating;
  if (t['toilets:wheelchair'] === 'yes') a.toilet = 'yes';
  if (['yes', 'only'].includes(t['diet:vegetarian'])) a.veg = t['diet:vegetarian'];
  if (['yes', 'only'].includes(t['diet:vegan'])) a.vegan = t['diet:vegan'];
  return a;
};

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = {}, unmatched = [], claimed = {};
  for (const el of raw.elements) {
    const a = pick(el.tags);
    if (!Object.keys(a).length) continue;
    const m = match(el);
    if (!m.slug) { if (m.why === 'no listing' || m.why === 'ambiguous') unmatched.push({ id: el.id, name: el.tags.name, why: m.why }); continue; }
    (claimed[m.slug] ||= []).push({ el, a });
  }
  for (const [slug, els] of Object.entries(claimed).sort()) {
    if (els.length > 1) { unmatched.push(...els.map(({ el }) => ({ id: el.id, name: el.tags.name, why: `one of ${els.length} map entries for ${slug}` }))); continue; }
    out[slug] = { ...els[0].a, osm: els[0].el.id };
  }
  writeFileSync(new URL('../src/data/attrs.mjs', import.meta.url), `// Visitor attributes per listing, from OpenStreetMap (© OpenStreetMap
// contributors, ODbL), pulled ${raw.pulled}. Generated by scripts/import-attrs.mjs
// from scripts/data/osm-attrs.json; don't edit by hand. Only what mappers
// recorded: a missing key means unknown, never "no".
export const ATTRS_PULLED = ${JSON.stringify(raw.pulled)};
export const ATTRS = ${JSON.stringify(out, null, 0)};
`);
  writeFileSync(new URL('./data/attrs-unmatched.json', import.meta.url), JSON.stringify(unmatched, null, 1));
  console.log(`${Object.keys(out).length} listings with attributes, ${unmatched.length} map entries left for a person`);
}
