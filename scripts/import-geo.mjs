// node scripts/import-geo.mjs <maps-geo.json>
// Map pins (and street address where we had none) for each business, from
// its own Google Maps listing. Writes src/data/geo.mjs.
import { readFileSync, writeFileSync } from 'node:fs';

const raw = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const out = {};
for (const [slug, r] of Object.entries(raw).sort()) {
  if (!Array.isArray(r) || typeof r[0] !== 'number') continue;
  const [lat, lng, addr] = r;
  // Columbus and the towns around it only; a pin in another state is a bad match.
  if (lat < 38.9 || lat > 39.5 || lng < -86.3 || lng > -85.5) continue;
  const street = String(addr || '').replace(/,\s*(Columbus|Hope|Taylorsville|Edinburgh|Elizabethtown|Seymour|Nashville|North Vernon),?\s*IN\s*\d{5}.*$/i, '').trim();
  out[slug] = street && street !== addr ? [lat, lng, street] : [lat, lng];
}
const head = `// Map pins per business ([lat, lng] and, where Google lists one, the street
// address), from each business's own Google Maps listing, October 2026.
// Generated by scripts/import-geo.mjs.
`;
writeFileSync(new URL('../src/data/geo.mjs', import.meta.url), head + 'export const GEO = ' + JSON.stringify(out) + ';\n');
console.log(Object.keys(out).length, 'pins');
