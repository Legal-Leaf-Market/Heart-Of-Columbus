// node scripts/import-web.mjs <maps-lookup.json>
// Turns the Google Maps lookup (website, phone, action links per slug) into
// src/data/web.mjs. Lookups that matched a different business are dropped.
import { readFileSync, writeFileSync } from 'node:fs';

const raw = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const clean = (u) => {
  try {
    const x = new URL(u);
    for (const k of [...x.searchParams.keys()]) if (/^(utm_|fbclid|gclid|rwg_token|source$|y_source)/.test(k)) x.searchParams.delete(k);
    return x.toString();
  } catch { return ''; }
};
const out = {};
for (const [slug, r] of Object.entries(raw).sort()) {
  if (r.miss || !r.h) continue;
  const row = {};
  if (r.w) row.website = clean(r.w);
  if (r.p) row.phone = r.p;
  if (r.o && r.o.length) row.actions = r.o.map(([l, u]) => [l, clean(u)]).filter(([, u]) => u);
  if (r.x) row.closed = true;
  if (r.t) row.tempClosed = true;
  if (Object.keys(row).length) out[slug] = row;
}
const head = `// Websites, phones and owner-set action links (order, book, menu) for each
// business, read from each business's own Google Maps listing, October 2026.
// Generated by scripts/import-web.mjs; regenerate rather than hand-edit.
`;
writeFileSync(new URL('../src/data/web.mjs', import.meta.url), head + 'export const WEB = ' + JSON.stringify(out, null, 1) + ';\n');
console.log(Object.keys(out).length, 'businesses with web data');
