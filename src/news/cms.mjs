// The CMS configuration (public/admin/), generated at build time from the
// same registries the build checks against, so the editor's dropdowns never
// drift from what the tests accept. Written to dist/admin/config.yml.
import { LABELS } from './labels.mjs';
import { SECTIONS } from './sections.mjs';
import { STAFF } from '../data/staff.mjs';

const q = (s) => JSON.stringify(String(s));
const opts = (pairs) => pairs.map(([label, value]) => `\n          - { label: ${q(label)}, value: ${q(value)} }`).join('');
const list = (name, label, fields, hint = '') => `
      - name: ${name}
        label: ${q(label)}
        widget: list
        required: false${hint ? `\n        hint: ${q(hint)}` : ''}
        fields:${fields.map((f) => `\n          - ${f}`).join('')}`;

export function cmsConfig() {
  const staff = Object.entries(STAFF).map(([slug, s]) => [`${s.name}, ${s.role}`, slug]);
  const editors = Object.entries(STAFF).filter(([, s]) => s.editor).map(([slug, s]) => [s.name, slug]);
  return `# Generated by build.mjs from src/news/cms.mjs. Edit that file, not this one.
# TODO(owner): choose the sign-in. git-gateway uses Netlify Identity; for
# GitHub OAuth use "name: github" and "repo: Legal-Leaf-Market/Heart-Of-Columbus".
backend:
  name: git-gateway
  branch: main
  squash_merges: true
  commit_messages:
    create: 'News: new story {{slug}}'
    update: 'News: update {{slug}}'
publish_mode: editorial_workflow
site_url: /news/
display_url: /news/
logo_url: /favicon.svg
media_folder: public/news-media
public_folder: /news-media
slug:
  encoding: ascii
  clean_accents: true
collections:
  - name: stories
    label: Stories
    label_singular: Story
    description: "Every story needs a named author and a different person as editor. The build refuses anything else."
    folder: content/stories
    path: '{{year}}/{{month}}/{{slug}}'
    slug: '{{fields.headline}}'
    identifier_field: headline
    create: true
    extension: md
    format: yaml-frontmatter
    summary: '{{label}} · {{headline}}'
    sortable_fields: [published, headline]
    fields:
      - { name: headline, label: Headline, widget: string }
      - { name: dek, label: "Dek (one sentence under the headline)", widget: string, required: false }
      - name: label
        label: Label
        widget: select
        hint: "What kind of story this is. Definitions are on /about/standards/#labels."
        options:${opts(Object.keys(LABELS).map((l) => [l, l]))}
      - name: section
        label: Section
        widget: select
        options:${opts(SECTIONS.map((s) => [s.name, s.slug]))}
      - name: bylines
        label: Bylines
        widget: select
        multiple: true
        min: 1
        options:${opts(staff)}
      - name: editor
        label: "Approving editor (not an author)"
        widget: select
        required: false
        options:${opts(editors)}
      - { name: published, label: Published, widget: datetime, format: 'YYYY-MM-DDTHH:mm:ssZ', hint: "Columbus time." }
      - { name: updated, label: Updated, widget: datetime, format: 'YYYY-MM-DDTHH:mm:ssZ', required: false }
      - { name: tags, label: Tags, widget: list, required: false, hint: "Business, landmark or neighborhood slugs from the site, or topics. Comma separated." }${list('sources', 'References', [
        '{ name: name, label: "Who or what", widget: string }',
        '{ name: url, label: Link, widget: string, required: false }',
        '{ name: note, label: "Note (for example: interview, October 24)", widget: string, required: false }',
      ], 'Each needs a link or a note.')}
      - { name: methods, label: "How we reported this", widget: text, required: false }${list('corrections', 'Corrections (add only, never edit or remove)', [
        '{ name: date, label: Date, widget: datetime, format: "YYYY-MM-DD", time_format: false }',
        '{ name: text, label: "What was wrong and what is right", widget: text }',
        '{ name: major, label: "Changes the meaning (show at the top)", widget: boolean, required: false }',
      ])}${list('images', 'Images', [
        '{ name: file, label: Image, widget: image }',
        '{ name: alt, label: "Alt text (what it shows)", widget: string }',
        '{ name: caption, label: Caption, widget: string, required: false }',
        '{ name: credit, label: Credit, widget: string }',
        '{ name: license, label: "License (Staff photo, used with permission, CC BY 4.0...)", widget: string }',
      ])}
      - { name: sponsor, label: "Sponsor (only for Sponsored)", widget: string, required: false }
      - name: developing
        label: "Developing story box"
        widget: object
        required: false
        collapsed: true
        fields:
          - { name: know, label: "What we know", widget: list }
          - { name: dontKnow, label: "What we don't know yet", widget: list }
      - { name: draft, label: "Draft (build it for preview, list it nowhere)", widget: boolean, required: false, default: false }
      - { name: body, label: Story, widget: markdown, buttons: [bold, italic, link, heading-two, heading-three, quote, bulleted-list, numbered-list], editor_components: [], modes: [rich_text, raw] }
`;
}
